// Development-only importer. Normal builds use the checked-in assets and Rust tables.
// NODE_PATH=/path/to/node_modules node scripts/generate-file-icons.mjs --source /path/to/material-icon-theme/package
import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir, rm, copyFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const version = '5.39.0';
const require = createRequire(import.meta.url);
const sharp = require('sharp');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceIndex = process.argv.indexOf('--source');
if (sourceIndex < 0 || !process.argv[sourceIndex + 1]) throw new Error('Pass --source with the extracted npm package directory');
const source = path.resolve(process.argv[sourceIndex + 1]);
const pkg = JSON.parse(await readFile(path.join(source, 'package.json'), 'utf8'));
if (pkg.name !== 'material-icon-theme' || pkg.version !== version) throw new Error(`Expected material-icon-theme ${version}`);
const upstream = JSON.parse(await readFile(path.join(source, 'dist/material-icons.json'), 'utf8'));
const definitions = upstream.iconDefinitions;
const names = { ...upstream.fileNames };
const extensions = { ...upstream.fileExtensions };
// Fill gaps for formats Glim reads, plus common macOS and engineering files.
Object.assign(names, { 'cargo.toml': 'rust', 'cargo.lock': 'lock', '.env': 'tune' });
for (const [icon, suffixes] of Object.entries({
  tree: ['xmind', 'opml'],
  markdown: ['org'],
  word: ['pages'],
  table: ['numbers'],
  powerpoint: ['keynote'],
  xml: ['gpx', 'kml', 'mtlx', 'tmx', 'dae', 'bpmn', 'xsl', 'xslt'],
  yaml: ['ocio'],
  image: ['procreate', 'avci', 'avcs', 'jxl', 'pfm', 'pam', 'dds', 'pvr', 'ktx', 'ktx2'],
  '3d': ['dwg', 'dxf', 'step', 'stp', 'iges', 'igs', '3mf', 'ply', 'abc'],
  font: ['ttc', 'dfont', 'suit', 'otc', 'pfa', 'pfb'],
  database: ['s3db', 'wal', 'shm', 'db-wal', 'db-shm', 'sqlite-wal', 'sqlite-shm', 'sqlite3-wal', 'sqlite3-shm'],
  email: ['vcf'],
})) for (const suffix of suffixes) extensions[suffix] ??= icon;

const rows = (mapping, lightMapping = {}) => Object.entries(mapping)
  .map(([name, dark]) => [name.toLowerCase(), dark, lightMapping[name] ?? dark])
  .sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
const nameRows = rows(names, upstream.light?.fileNames);
const extensionRows = rows(extensions, upstream.light?.fileExtensions);
// Runtime prefix/context rules reference the same inventory as exact associations.
const patterns = ['docker', 'tune', 'github-actions-workflow'];
const used = [...new Set([upstream.file, ...patterns, ...nameRows.flatMap(row => row.slice(1)), ...extensionRows.flatMap(row => row.slice(1))])].sort();
// The loader binary-searches full filenames: '-' sorts before '.', so sorting
// bare icon IDs puts python.png before python-misc.png and breaks lookup.
const assetOrder = [...used].sort((a, b) => {
  const left = `file-icons/${a}.png`, right = `file-icons/${b}.png`;
  return left < right ? -1 : left > right ? 1 : 0;
});
for (const icon of used) if (!definitions[icon]) throw new Error(`Missing icon definition: ${icon}`);
for (const entries of [nameRows, extensionRows]) {
  for (let i = 1; i < entries.length; i++) if (entries[i][0] === entries[i - 1][0]) throw new Error(`Duplicate case-insensitive association: ${entries[i][0]}`);
}

// Decode every source before replacing tracked assets, so invalid input fails early.
const images = [];
for (const icon of used) {
  const svgPath = path.resolve(source, 'dist', definitions[icon].iconPath);
  if (!svgPath.startsWith(path.join(source, 'icons') + path.sep)) throw new Error('Icon path escapes package icons');
  const svg = await readFile(svgPath);
  const png = await sharp(svg).resize(48, 48, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } }).png().toBuffer();
  images.push({ icon, svg, png });
}
const output = path.join(root, 'assets/file-icons');
await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
for (const { icon, svg, png } of images) {
  await writeFile(path.join(output, `${icon}.svg`), svg);
  await writeFile(path.join(output, `${icon}.png`), png);
}
await copyFile(path.join(source, 'LICENSE'), path.join(output, 'LICENSE'));
const quote = value => JSON.stringify(value);
const table = (name, entries) => `pub(super) static ${name}: &[(&str, &str, &str)] = &[\n${entries.map(row => `    (${row.map(quote).join(', ')}),`).join('\n')}\n];\n`;
await writeFile(path.join(root, 'crates/glim-app/src/views/file_icons_data.rs'),
  '// Generated by scripts/generate-file-icons.mjs; do not edit.\n' +
  `pub(super) const DEFAULT: &str = ${quote(upstream.file)};\n` +
  table('PATH_NAMES', nameRows.filter(row => row[0].includes('/'))) +
  table('FILE_NAMES', nameRows.filter(row => !row[0].includes('/'))) + table('EXTENSIONS', extensionRows));
await writeFile(path.join(root, 'crates/glim-app/src/app/file_icon_assets.rs'),
  '// Generated by scripts/generate-file-icons.mjs; do not edit.\n' +
  `pub(super) const FALLBACK: &[u8] = include_bytes!("../../../../assets/file-icons/${upstream.file}.png");\n` +
  'pub(super) static ASSETS: &[(&str, &[u8])] = &[\n' + assetOrder.map(icon =>
    `    ("file-icons/${icon}.png", include_bytes!("../../../../assets/file-icons/${icon}.png")),`).join('\n') + '\n];\n');
await writeFile(path.join(output, 'manifest.json'), JSON.stringify({
  source: `material-icon-theme@${version}`,
  archive: `https://registry.npmjs.org/material-icon-theme/-/material-icon-theme-${version}.tgz`,
  integrity: 'sha512-6dUQXJgNBlklaILIOlCZXhSBTsBmLkt11XMoTY7Uyb4ZikelGgZHOY4AdOWBA+SXz51cVWfOVnTHrTwGM91eYw==',
  default: upstream.file, icons: used,
  fileNames: Object.fromEntries(nameRows.map(([name, dark, light]) => [name, { dark, light }])),
  extensions: Object.fromEntries(extensionRows.map(([name, dark, light]) => [name, { dark, light }])),
}, null, 2) + '\n');
await writeFile(path.join(output, 'README.md'), `# File icons

Material Icon Theme ${version}, under the MIT license (see LICENSE). SVG originals and 48 px transparent PNGs are checked in; normal app builds need no Node.js, network or image conversion tools. The npm archive and its integrity hash are recorded in manifest.json.

Coverage: ${used.length} icon assets, ${extensionRows.length} extension rules and ${nameRows.length} exact filename rules, including light-theme variants. Directory-qualified filename rules take precedence over basenames and longest compound suffixes. Embedded assets are sorted by complete resource paths (including .png), matching the runtime binary search. Glim also handles Dockerfile/Containerfile variants, Compose variants, environment variants and GitHub Actions workflow directories. Icons identify files; they do not imply reader or editing support.

Regenerate with NODE_PATH=/path/to/node_modules node scripts/generate-file-icons.mjs --source /path/to/extracted/material-icon-theme/package (requires sharp). The importer pins the package version, adds Glim's format associations, and generates both Rust tables from the same inventory. Run cargo fmt --all afterward.
`);
console.log(`Generated ${used.length} icons, ${extensionRows.length} extension rules, ${nameRows.length} filename rules.`);
